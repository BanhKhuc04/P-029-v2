"""Controlled CPU training smoke; two tuning scene files, two seeds, two epochs.

Use only local checkpoints generated by this review. No deployment or quality acceptance.
Run with a PyTorch environment; optional Windows DLL directory is supplied by the caller.
"""
import argparse
import contextlib
import hashlib
import io
import json
from pathlib import Path
import runpy
import sys

ROOT = Path(__file__).resolve().parents[4]
TOOL = ROOT / "source-tool/pointsnap-3d"
sys.path.insert(0, str(TOOL))


def main():
    import numpy as np
    import torch
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--summary", type=Path, required=True)
    args = parser.parse_args()
    if args.out_dir.exists() or args.summary.exists():
        parser.error("Choose fresh output paths")
    args.out_dir.mkdir(parents=True)
    torch.set_num_threads(1)
    script = TOOL / "scripts/train_critic_example.py"
    logs, paths = [], []
    for i in range(2):
        path = args.out_dir / f"ensemble-{i}.pt"
        argv = sys.argv
        sys.argv = [str(script), "--data", str(args.data), "--epochs", "2", "--batch", "32", "--width", "16",
                    "--ensemble", "2", "--seed", "11", "--quiet", "--out", str(path)]
        output = io.StringIO()
        try:
            with contextlib.redirect_stdout(output):
                runpy.run_path(str(script), run_name="__main__")
        finally:
            sys.argv = argv
        logs.append(output.getvalue().splitlines())
        paths.append(path)
    val_path = args.data / "scene-0553.npz"
    with np.load(val_path, allow_pickle=False) as data:
        points, meta = torch.from_numpy(data["points"]), torch.from_numpy(data["meta"])
        clean = np.all(data["target"] == 0, axis=1)
    first = torch.jit.load(str(paths[0]), map_location="cpu").eval()
    second = torch.jit.load(str(paths[1]), map_location="cpu").eval()
    with torch.inference_mode():
        logit, delta = first(points, meta)
        other_logit, other_delta = second(points, meta)
        members = [m(points, meta) for _, m in first.members.named_children()]
    p = torch.sigmoid(logit).numpy()
    summary = {"torch": torch.__version__, "device": "cpu", "cuda_available": torch.cuda.is_available(),
               "train_scene": "scene-0061", "validation_scene": "scene-0553", "test_scenes_used": [],
               "epochs": 2, "ensemble_seeds": [11, 12], "batch": 32, "width": 16,
               "validation_samples": len(meta), "checkpoint_shapes": [list(logit.shape), list(delta.shape)],
               "finite_outputs": bool(torch.isfinite(logit).all() and torch.isfinite(delta).all()),
               "repeat_logit_max_abs": float((logit-other_logit).abs().max()),
               "repeat_delta_max_abs": float((delta-other_delta).abs().max()),
               "ensemble_logit_max_abs": float((logit-torch.stack([v[0] for v in members]).mean(0)).abs().max()),
               "ensemble_delta_max_abs": float((delta-torch.stack([v[1] for v in members]).mean(0)).abs().max()),
               "suggested_raw_score_threshold": float(np.quantile(p[clean], .99)),
               "logs": logs, "checkpoint_sha256": [hashlib.sha256(path.read_bytes()).hexdigest() for path in paths],
               "training_source_sha256": hashlib.sha256(script.read_bytes()).hexdigest(),
               "interpretation": "execution and reproducibility smoke only; no quality or calibration acceptance"}
    assert summary["finite_outputs"]
    assert all(summary[k] == 0 for k in ["repeat_logit_max_abs", "repeat_delta_max_abs",
                                        "ensemble_logit_max_abs", "ensemble_delta_max_abs"])
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    args.summary.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps({k: v for k, v in summary.items() if k not in ("logs", "checkpoint_sha256")}))


if __name__ == "__main__":
    main()
